const {chromium}=require("playwright");
const assert=require("node:assert/strict");
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto("http://127.0.0.1:3100");
 const selects=page.locator("form select");
 console.log(await selects.evaluateAll(es=>es.map(e=>({id:e.id,options:[...e.options].map(o=>o.value)}))));
 await selects.nth(0).selectOption("Club Car");
 await selects.nth(1).selectOption("Onward");
 // Use actual form controls; year is a numeric input.
 await page.locator("form input[type=number]").first().fill("2023");
 await selects.nth(2).selectOption("Good");
 await selects.nth(4).selectOption("Lithium");
 await page.getByRole("button",{name:"Estimate my cart's value"}).click();
 await page.getByText("Sample 2023 Club Car Onward",{exact:true}).waitFor();
 await page.getByRole("heading",{name:"Verified comparable carts"}).scrollIntoViewIfNeeded();
 await page.screenshot({path:"/tmp/cartiq-comps-desktop.png"});
 await page.getByLabel("Seats for matching").selectOption("2");
 assert.equal(await page.getByText("Your Estimated Value",{exact:true}).count(),0);
 await page.getByRole("button",{name:"Growth scorecard",exact:true}).click();
 await page.getByText("4,200",{exact:true}).waitFor();
 await page.screenshot({path:"/tmp/cartiq-growth-desktop.png"});
 await page.getByText("Import Search Console totals",{exact:true}).click();
 await page.getByLabel("Impressions",{exact:true}).fill("100");
 await page.getByLabel("Clicks",{exact:true}).fill("2");
 await page.getByRole("button",{name:"Save search snapshot"}).click();
 await page.getByRole("button",{name:"Refresh scorecard"}).click();
 await page.getByText("4,200",{exact:true}).waitFor();
 await page.getByLabel("Preview state").selectOption("empty");
 await page.getByText("Not imported",{exact:true}).first().waitFor();
 await page.getByLabel("Preview state").selectOption("error");
 await page.getByRole("alert").waitFor();
 await page.getByLabel("Preview state").selectOption("ready");
 await page.getByText("4,200",{exact:true}).waitFor();
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:"/tmp/cartiq-growth-mobile.png",fullPage:true});
 await page.getByRole("button",{name:"Estimator + comps"}).click();
 async function estimate(){
   const s=page.locator("form select");
   await s.nth(0).selectOption("Club Car");await s.nth(1).selectOption("Onward");
   await page.locator("form input[type=number]").first().fill("2023");
   await s.nth(2).selectOption("Good");await s.nth(4).selectOption("Lithium");
   await page.getByRole("button",{name:"Estimate my cart's value"}).click();
 }
 await estimate();
 await page.getByText("Sample 2023 Club Car Onward",{exact:true}).waitFor();
 await page.getByRole("heading",{name:"Verified comparable carts"}).scrollIntoViewIfNeeded();
 await page.screenshot({path:"/tmp/cartiq-comps-mobile.png",fullPage:true});
 await page.getByLabel("Preview state").selectOption("empty");await estimate();
 await page.getByText("No recently source-verified close matches.",{exact:true}).waitFor();
 await page.getByLabel("Preview state").selectOption("error");await estimate();
 await page.getByRole("button",{name:"Retry comparable search"}).click();
 await page.getByRole("button",{name:"Retry comparable search"}).waitFor();
 await page.getByLabel("Preview state").selectOption("ready");
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:"/tmp/cartiq-estimator-mobile.png",fullPage:true});
 assert.deepEqual(errors,[]);
 console.log("Browser QA passed: estimator submission, source-checked card, stale-result clearing, scorecard tabs, import, refresh, scorecard and comps empty/error states, retry, mobile width and runtime errors.");
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
